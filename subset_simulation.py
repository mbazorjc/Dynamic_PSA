"""
subset_simulation.py
====================
Standard Subset Simulation (Au & Beck 2001) applied to the hardware-and-operator
model ("model H") of the two-pump shutdown-cooling system, written as a static
limit-state problem in the space of five standard-normal inputs:

  z1 -> failure time of running pump A (time-dependent Weibull item hazards)
  z2 -> common-cause vs independent failure (alpha-factor)
  z3 -> operator restart time (lognormal)
  z4 -> failure to start of pump B
  z5 -> run time to failure of pump B (FTR<=1h / >1h, Weibull items)

  g(z) = T_sys(z) - T_m,   failure  <=>  g <= 0,

where T_sys is the time of loss of shutdown cooling (failure of B, failure to
start, boiling before restart, or common-cause failure). Two variants:
  'dynamic'  time-dependent hazards and decay-heat-dependent time to boil;
  'static'   constant rates and the time to boil frozen at POS entry
             (the assumptions of a static fault tree).
Intermediate levels use conditional samples generated by component-wise
Markov-chain moves, p0 = 0.1, N samples per level.
Usage: python subset_simulation.py
"""
import json, time
import numpy as np
from scipy.special import ndtr
import dft_vs_mc as D
from nhmc_core import time_to_boil

T = D.T
TH = D.TH
SIG = D.SIG


def build_inverse(cum, tmax=2e6, n=40000):
    grid = np.concatenate([np.linspace(0, 200, n // 2), np.logspace(np.log10(200.01), np.log10(tmax), n // 2)])
    H = cum(grid)
    return grid, H


GA, HA = build_inverse(lambda t: D.cumA(t))
GB, HB = build_inverse(lambda u: D.cumB(u))
lbar = (TH["lam_b1"] + TH["lam_b2"] * (T - 1)) / T
tb0 = D.tb(0.0)


def system_time(z, variant="dynamic"):
    u = ndtr(z)
    e1, e5 = -np.log1p(-u[:, 0]), -np.log1p(-u[:, 4])   # unit-exponential variates
    if variant == "dynamic":
        tA = np.interp(e1, HA, GA, right=np.inf)
        tB = np.interp(e5, HB, GB, right=np.inf)
        fin = np.isfinite(tA)
        tb = np.where(fin, time_to_boil(D.p.t0 + np.where(fin, tA, 0.0), TH["M"], D.p), np.inf)
    else:
        tA = e1 / TH["lam_run"]
        tB = e5 / lbar
        tb = np.full(len(z), tb0)
    ccf = u[:, 1] < TH["alpha2"]
    tau = np.exp(np.log(TH["med_h"]) + SIG * z[:, 2])
    fts = u[:, 3] < TH["q_fts"]
    Ts = np.where(ccf, tA,
         np.where(tau >= tb, tA + tb,
         np.where(fts, tA + tau, tA + tau + tB)))
    return Ts


def g(z, variant):
    return system_time(z, variant) - T


def subset_simulation(variant, N=1000, p0=0.1, rng=None, max_levels=12):
    d = 5
    z = rng.standard_normal((N, d))
    gz = g(z, variant)
    n_eval = N
    P = 1.0
    nc = int(N * p0); ns = int(1 / p0)
    for level in range(max_levels):
        order = np.argsort(gz)
        b = gz[order[nc - 1]]
        if b <= 0:
            return P * np.mean(gz <= 0), n_eval, level + 1
        P *= p0
        seeds, gseeds = z[order[:nc]], gz[order[:nc]]
        newz, newg = [], []
        cur, gcur = seeds.copy(), gseeds.copy()
        for _ in range(ns):                       # grow nc chains in parallel
            cand = cur + rng.uniform(-1, 1, cur.shape)
            ratio = np.exp(-0.5 * (cand ** 2 - cur ** 2))
            keep = rng.random(cur.shape) < np.minimum(1, ratio)
            cand = np.where(keep, cand, cur)
            gc = g(cand, variant); n_eval += len(cand)
            acc = gc <= b
            cur = np.where(acc[:, None], cand, cur); gcur = np.where(acc, gc, gcur)
            newz.append(cur.copy()); newg.append(gcur.copy())
        z = np.concatenate(newz); gz = np.concatenate(newg)
    return P * np.mean(gz <= 0), n_eval, max_levels


if __name__ == "__main__":
    ref = json.load(open("dft_vs_mc.json"))
    # reference values: exact integral for the dynamic variant; for the static variant the
    # limit-state model differs slightly from the CTMC-converted DFT (restart delay), so a
    # 2e7-sample crude estimate of the same limit state is used as reference
    exact = {"dynamic": ref["model_H"]["P_exact"]}
    rng0 = np.random.default_rng(99)
    exact["static"] = float(np.mean([np.mean(g(rng0.standard_normal((2_000_000, 5)), "static") <= 0)
                                     for _ in range(10)]))
    print("static reference (2e7 crude):", exact["static"], flush=True)
    out = {}
    for variant in ("static", "dynamic"):
        rng = np.random.default_rng(11 if variant == "static" else 12)
        R = 100
        est, ne, lev, tt = [], [], [], []
        for r in range(R):
            t1 = time.perf_counter()
            P, n, L = subset_simulation(variant, rng=rng)
            tt.append(time.perf_counter() - t1); est.append(P); ne.append(n); lev.append(L)
        est = np.array(est)
        # crude Monte Carlo with the same number of model evaluations
        nmean = int(np.mean(ne))
        t1 = time.perf_counter()
        crude = np.array([np.mean(g(rng.standard_normal((nmean, 5)), variant) <= 0) for _ in range(R)])
        tcr = (time.perf_counter() - t1) / R
        out[variant] = dict(exact=exact[variant], sus_mean=float(est.mean()), sus_cov=float(est.std(ddof=1) / est.mean()),
                            sus_bias=float((est.mean() - exact[variant]) / exact[variant]),
                            n_eval_mean=nmean, levels_mean=float(np.mean(lev)), time_s=float(np.mean(tt)),
                            crude_mean=float(crude.mean()), crude_cov=float(crude.std(ddof=1) / crude.mean()),
                            crude_time_s=tcr, R=R)
        print(variant, out[variant], flush=True)
        # check the limit-state model itself with a large crude sample
        big = np.mean(g(rng.standard_normal((2_000_000, 5)), variant) <= 0)
        out[variant]["crude_2e6"] = float(big)
        print("  crude 2e6:", big, " exact:", exact[variant], flush=True)
    json.dump(out, open("subset_simulation.json", "w"), indent=1)
